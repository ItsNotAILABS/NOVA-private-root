export interface KuramotoOscillator {
  id: number;
  phase: number;              // θ ∈ [0, 2π)
  omega: number;              // Natural frequency (rad/s)
  amplitude: number;          // Oscillation amplitude
  damping: number;            // Damping coefficient
  localOrder: number;         // Local order parameter
}

export interface KuramotoNetwork {
  oscillators: KuramotoOscillator[];
  N: number;                  // Number of oscillators
  K: number;                  // Global coupling strength
  rGlobal: number;            // Global order parameter
  psiGlobal: number;          // Global mean phase
  entropy: number;            // System entropy
  beat: number;
}

/**
 * KURAMOTO ORDER PARAMETER COMPUTATION
 * 
 * The order parameter r·e^(iψ) measures global synchronization:
 *   r·e^(iψ) = (1/N) Σⱼ e^(iθⱼ)
 * 
 * When r → 1: Perfect synchronization (all phases aligned)
 * When r → 0: Complete disorder (uniform phase distribution)
 * When r ≈ φ⁻¹ ≈ 0.618: Critical transition point (Medina threshold)
 */
export function computeKuramotoOrder(oscillators: KuramotoOscillator[]): { r: number; psi: number } {
  const N = oscillators.length;
  if (N === 0) return { r: SIGMA_ZERO, psi: 0 };

  let sumCos = 0;
  let sumSin = 0;
  let totalWeight = 0;

  for (const osc of oscillators) {
    const weight = osc.amplitude;
    sumCos += weight * Math.cos(osc.phase);
    sumSin += weight * Math.sin(osc.phase);
    totalWeight += weight;
  }

  if (totalWeight < 0.0001) return { r: SIGMA_ZERO, psi: 0 };

  const avgCos = sumCos / totalWeight;
  const avgSin = sumSin / totalWeight;

  // Order parameter magnitude
  const rRaw = Math.sqrt(avgCos * avgCos + avgSin * avgSin);
  
  // Apply sovereign floor with smooth transition
  const rFloor = SIGMA_ZERO;
  const r = rRaw < rFloor 
    ? rFloor + (rRaw - rFloor) * Math.tanh(rRaw / rFloor * π)
    : rRaw;

  // Mean phase
  let psi = Math.atan2(avgSin, avgCos);
  if (psi < 0) psi += τ;

  return { r, psi };
}

/**
 * KURAMOTO PHASE UPDATE (Mean-Field Approximation)
 * 
 * The Kuramoto model with mean-field approximation:
 *   dθᵢ/dt = ωᵢ + K·r·sin(ψ - θᵢ)
 * 
 * This gives O(N) complexity instead of O(N²) for direct coupling.
 * 
 * @param osc - Oscillator to update
 * @param r - Global order parameter
 * @param psi - Global mean phase
 * @param K - Coupling strength
 * @param dt - Time step
 * @returns Updated phase
 */
export function kuramotoPhaseUpdate(
  osc: KuramotoOscillator,
  r: number,
  psi: number,
  K: number,
  dt: number
): number {
  // Mean-field coupling: K·r·sin(ψ - θ)
  const coupling = K * r * Math.sin(psi - osc.phase);
  
  // Phase velocity with damping
  const dPhasedt = osc.omega + coupling - osc.damping * (osc.omega - 1);
  
  // Euler integration
  let newPhase = osc.phase + dPhasedt * dt;
  
  // Normalize to [0, 2π)
  while (newPhase < 0) newPhase += τ;
  while (newPhase >= τ) newPhase -= τ;
  
  return newPhase;
}

/**
 * RUNGE-KUTTA 4TH ORDER KURAMOTO UPDATE
 * 
 * For higher accuracy when dt is large:
 *   k1 = f(t, y)
 *   k2 = f(t + dt/2, y + dt·k1/2)
 *   k3 = f(t + dt/2, y + dt·k2/2)
 *   k4 = f(t + dt, y + dt·k3)
 *   y_new = y + (dt/6)(k1 + 2k2 + 2k3 + k4)
 */
export function kuramotoRK4Update(
  osc: KuramotoOscillator,
  r: number,
  psi: number,
  K: number,
  dt: number
): number {
  const f = (phase: number) => osc.omega + K * r * Math.sin(psi - phase);
  
  const k1 = f(osc.phase);
  const k2 = f(osc.phase + 0.5 * dt * k1);
  const k3 = f(osc.phase + 0.5 * dt * k2);
  const k4 = f(osc.phase + dt * k3);
  
  let newPhase = osc.phase + (dt / 6) * (k1 + 2*k2 + 2*k3 + k4);
  
  while (newPhase < 0) newPhase += τ;
  while (newPhase >= τ) newPhase -= τ;
  
  return newPhase;
}

/**
 * FULL KURAMOTO NETWORK TICK
 * 
 * Updates all oscillators using mean-field approximation.
 * Computes global metrics (order parameter, entropy).
 */
export function tickKuramotoNetwork(network: KuramotoNetwork, dt: number): KuramotoNetwork {
  // Step 1: Compute global order parameter
  const { r: rGlobal, psi: psiGlobal } = computeKuramotoOrder(network.oscillators);
  
  // Step 2: Update each oscillator
  const newOscillators = network.oscillators.map(osc => {
    const newPhase = kuramotoRK4Update(osc, rGlobal, psiGlobal, network.K, dt);
    
    // Compute local order parameter (from neighbors would require adjacency)
    // Here we use global as proxy
    const localOrder = rGlobal;
    
    return {
      ...osc,
      phase: newPhase,
      localOrder
    };
  });
  
  // Step 3: Compute entropy
  const entropy = computePhaseEntropy(newOscillators);
  
  return {
    ...network,
    oscillators: newOscillators,
    rGlobal,
    psiGlobal,
    entropy,
    beat: network.beat + 1
  };
}

/**
 * PHASE ENTROPY COMPUTATION
 * 
 * Entropy measures disorder in the phase distribution:
 *   S = -Σᵢ pᵢ log(pᵢ)
 * 
 * We bin phases into 36 bins (10° each) and compute histogram entropy.
 */
export function computePhaseEntropy(oscillators: KuramotoOscillator[]): number {
  const NUM_BINS = 36;
  const bins = new Array(NUM_BINS).fill(0);
  let totalWeight = 0;
  
  for (const osc of oscillators) {
    const binIndex = Math.floor((osc.phase / τ) * NUM_BINS) % NUM_BINS;
    bins[binIndex] += osc.amplitude;
    totalWeight += osc.amplitude;
  }
  
  if (totalWeight < 0.0001) return 0;
  
  let entropy = 0;
  for (const count of bins) {
    const p = count / totalWeight;
    if (p > 0.0001) {
      entropy -= p * Math.log(p);
    }
  }
  
  // Normalize by maximum entropy
  const maxEntropy = Math.log(NUM_BINS);
  return entropy / maxEntropy;
}

