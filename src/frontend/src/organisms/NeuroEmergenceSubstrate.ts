/**
 * PERLIN-LIKE NOISE (Simplified)
 * 
 * Gradient noise using hash function for pseudo-random gradients.
 */
export function noise2D(x: number, y: number, seed: number = 0): number {
  // Integer cell coordinates
  const ix = Math.floor(x);
  const iy = Math.floor(y);
  
  // Fractional part
  const fx = x - ix;
  const fy = y - iy;
  
  // Smoothstep interpolation weights
  const u = fx * fx * (3 - 2 * fx);
  const v = fy * fy * (3 - 2 * fy);
  
  // Hash function for pseudo-random
  const hash = (xi: number, yi: number) => {
    const h = (xi * 374761393 + yi * 668265263 + seed) % 1000000;
    return (h / 1000000) * 2 - 1; // [-1, 1]
  };
  
  // Four corner values
  const n00 = hash(ix, iy);
  const n10 = hash(ix + 1, iy);
  const n01 = hash(ix, iy + 1);
  const n11 = hash(ix + 1, iy + 1);
  
  // Bilinear interpolation
  const nx0 = n00 * (1 - u) + n10 * u;
  const nx1 = n01 * (1 - u) + n11 * u;
  
  return nx0 * (1 - v) + nx1 * v;
}

/**
 * FRACTAL BROWNIAN MOTION (fBm)
 * 
 * Layered noise with decreasing amplitude and increasing frequency:
 *   fbm(x) = Σᵢ aⁱ · noise(fⁱ · x)
 * 
 * where a is amplitude decay (persistence) and f is frequency multiplier (lacunarity).
 */
export function fbm(
  x: number,
  y: number,
  octaves: number = 6,
  persistence: number = 0.5,
  lacunarity: number = 2.0,
  seed: number = 0
): number {
  let total = 0;
  let amplitude = 1;
  let frequency = 1;
  let maxValue = 0;
  
  for (let i = 0; i < octaves; i++) {
    total += amplitude * noise2D(x * frequency, y * frequency, seed + i * 1000);
    maxValue += amplitude;
    amplitude *= persistence;
    frequency *= lacunarity;
  }
  
  return total / maxValue;
}

