export const QuaternionMath = {
  identity: (): Quaternion => ({ w: 1, x: 0, y: 0, z: 0 }),

  // Create from axis-angle representation
  fromAxisAngle: (axis: Vec3, angle: number): Quaternion => {
    const halfAngle = angle / 2;
    const s = Math.sin(halfAngle);
    const normalAxis = Vec3Math.normalize(axis);
    return {
      w: Math.cos(halfAngle),
      x: normalAxis.x * s,
      y: normalAxis.y * s,
      z: normalAxis.z * s
    };
  },

  // Create from Euler angles (XYZ order)
  fromEuler: (pitch: number, yaw: number, roll: number): Quaternion => {
    const cy = Math.cos(yaw * 0.5);
    const sy = Math.sin(yaw * 0.5);
    const cp = Math.cos(pitch * 0.5);
    const sp = Math.sin(pitch * 0.5);
    const cr = Math.cos(roll * 0.5);
    const sr = Math.sin(roll * 0.5);

    return {
      w: cr * cp * cy + sr * sp * sy,
      x: sr * cp * cy - cr * sp * sy,
      y: cr * sp * cy + sr * cp * sy,
      z: cr * cp * sy - sr * sp * cy
    };
  },

  // Quaternion multiplication: q1 * q2
  multiply: (q1: Quaternion, q2: Quaternion): Quaternion => ({
    w: q1.w * q2.w - q1.x * q2.x - q1.y * q2.y - q1.z * q2.z,
    x: q1.w * q2.x + q1.x * q2.w + q1.y * q2.z - q1.z * q2.y,
    y: q1.w * q2.y - q1.x * q2.z + q1.y * q2.w + q1.z * q2.x,
    z: q1.w * q2.z + q1.x * q2.y - q1.y * q2.x + q1.z * q2.w
  }),

  // Conjugate: q* = (w, -x, -y, -z)
  conjugate: (q: Quaternion): Quaternion => ({
    w: q.w,
    x: -q.x,
    y: -q.y,
    z: -q.z
  }),

  // Magnitude
  magnitude: (q: Quaternion): number =>
    Math.sqrt(q.w * q.w + q.x * q.x + q.y * q.y + q.z * q.z),

  // Normalize
  normalize: (q: Quaternion): Quaternion => {
    const mag = QuaternionMath.magnitude(q);
    if (mag < 0.000001) return QuaternionMath.identity();
    return {
      w: q.w / mag,
      x: q.x / mag,
      y: q.y / mag,
      z: q.z / mag
    };
  },

  // Inverse: q^(-1) = q* / |q|²
  inverse: (q: Quaternion): Quaternion => {
    const magSq = q.w * q.w + q.x * q.x + q.y * q.y + q.z * q.z;
    if (magSq < 0.000001) return QuaternionMath.identity();
    return {
      w: q.w / magSq,
      x: -q.x / magSq,
      y: -q.y / magSq,
      z: -q.z / magSq
    };
  },

  // Rotate a vector by quaternion: v' = q * v * q^(-1)
  rotateVector: (q: Quaternion, v: Vec3): Vec3 => {
    // Optimized implementation
    const qv: Vec3 = { x: q.x, y: q.y, z: q.z };
    const uv = Vec3Math.cross(qv, v);
    const uuv = Vec3Math.cross(qv, uv);
    
    return Vec3Math.add(
      v,
      Vec3Math.add(
        Vec3Math.scale(uv, 2 * q.w),
        Vec3Math.scale(uuv, 2)
      )
    );
  },

  // Spherical linear interpolation
  slerp: (q1: Quaternion, q2: Quaternion, t: number): Quaternion => {
    let dot = q1.w * q2.w + q1.x * q2.x + q1.y * q2.y + q1.z * q2.z;
    
    // If dot is negative, negate one quaternion to take shorter path
    let q2Adjusted = q2;
    if (dot < 0) {
      q2Adjusted = { w: -q2.w, x: -q2.x, y: -q2.y, z: -q2.z };
      dot = -dot;
    }
    
    // If very close, use linear interpolation
    if (dot > 0.9995) {
      const result = {
        w: q1.w + t * (q2Adjusted.w - q1.w),
        x: q1.x + t * (q2Adjusted.x - q1.x),
        y: q1.y + t * (q2Adjusted.y - q1.y),
        z: q1.z + t * (q2Adjusted.z - q1.z)
      };
      return QuaternionMath.normalize(result);
    }
    
    const theta0 = Math.acos(dot);
    const theta = theta0 * t;
    const sinTheta = Math.sin(theta);
    const sinTheta0 = Math.sin(theta0);
    
    const s0 = Math.cos(theta) - dot * sinTheta / sinTheta0;
    const s1 = sinTheta / sinTheta0;
    
    return {
      w: s0 * q1.w + s1 * q2Adjusted.w,
      x: s0 * q1.x + s1 * q2Adjusted.x,
      y: s0 * q1.y + s1 * q2Adjusted.y,
      z: s0 * q1.z + s1 * q2Adjusted.z
    };
  },

  // Convert to Euler angles
  toEuler: (q: Quaternion): { pitch: number; yaw: number; roll: number } => {
    // Roll (x-axis rotation)
    const sinrCosp = 2 * (q.w * q.x + q.y * q.z);
    const cosrCosp = 1 - 2 * (q.x * q.x + q.y * q.y);
    const roll = Math.atan2(sinrCosp, cosrCosp);

    // Pitch (y-axis rotation)
    const sinp = 2 * (q.w * q.y - q.z * q.x);
    let pitch: number;
    if (Math.abs(sinp) >= 1) {
      pitch = Math.sign(sinp) * π / 2; // Gimbal lock
    } else {
      pitch = Math.asin(sinp);
    }

    // Yaw (z-axis rotation)
    const sinyCosp = 2 * (q.w * q.z + q.x * q.y);
    const cosyCosp = 1 - 2 * (q.y * q.y + q.z * q.z);
    const yaw = Math.atan2(sinyCosp, cosyCosp);

    return { pitch, yaw, roll };
  }
};

