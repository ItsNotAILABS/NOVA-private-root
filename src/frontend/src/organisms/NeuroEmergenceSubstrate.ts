// SECTION 6: VAN DER POL OSCILLATOR (Heartbeat Dynamics)
// ═══════════════════════════════════════════════════════════════════════════════

export interface VanDerPolState {
  x: number;      // Position
  v: number;      // Velocity
  mu: number;     // Nonlinearity parameter
  omega: number;  // Natural frequency
}

/**
 * VAN DER POL OSCILLATOR DERIVATIVES
 * 
 * The Van der Pol oscillator:
 *   dx/dt = v
 *   dv/dt = μ(1 - x²)v - ω²x + F_ext
 * 
 * The term μ(1 - x²) provides:
 *   - Negative damping when |x| < 1 (energy injection)
 *   - Positive damping when |x| > 1 (energy dissipation)
 * This creates a stable limit cycle (self-sustaining oscillation).
 */
export function vanDerPolDerivatives(
  state: VanDerPolState,
  externalForce: number = 0
): { dx: number; dv: number } {
  const dx = state.v;
  const dv = state.mu * (1 - state.x * state.x) * state.v 
           - state.omega * state.omega * state.x 
           + externalForce;
  return { dx, dv };
}

/**
 * RK4 INTEGRATION FOR VAN DER POL
 */
export function integrateVanDerPol(
  state: VanDerPolState,
  externalForce: number,
  dt: number
): VanDerPolState {
  const f = (x: number, v: number) => {
    const tempState = { ...state, x, v };
    return vanDerPolDerivatives(tempState, externalForce);
  };
  
  const k1 = f(state.x, state.v);
  const k2 = f(state.x + 0.5 * dt * k1.dx, state.v + 0.5 * dt * k1.dv);
  const k3 = f(state.x + 0.5 * dt * k2.dx, state.v + 0.5 * dt * k2.dv);
  const k4 = f(state.x + dt * k3.dx, state.v + dt * k3.dv);
  
  return {
    ...state,
    x: state.x + (dt / 6) * (k1.dx + 2*k2.dx + 2*k3.dx + k4.dx),
    v: state.v + (dt / 6) * (k1.dv + 2*k2.dv + 2*k3.dv + k4.dv)
  };
}

