/**
 * FIBONACCI NUMBER COMPUTATION
 * 
 * Using Binet's formula (closed form):
 *   F(n) = (φⁿ - ψⁿ) / √5
 * 
 * This is exact for n < ~70 due to floating point precision.
 */
export function fibonacci(n: number): number {
  if (n < 0) return 0;
  if (n < FIB.length) return FIB[n];
  
  // Binet's formula for larger n
  return Math.round((Math.pow(φ, n) - Math.pow(-ψ, n)) / SQRT_5);
}

/**
 * Check if n is a Fibonacci number
 * 
 * A number is Fibonacci iff 5n² + 4 or 5n² - 4 is a perfect square.
 */
export function isFibonacci(n: number): boolean {
  if (n < 0) return false;
  if (n === 0 || n === 1) return true;
  
  const test1 = 5 * n * n + 4;
  const test2 = 5 * n * n - 4;
  
  const sqrt1 = Math.sqrt(test1);
  const sqrt2 = Math.sqrt(test2);
  
  return Math.floor(sqrt1) * Math.floor(sqrt1) === test1 ||
         Math.floor(sqrt2) * Math.floor(sqrt2) === test2;
}

/**
 * Find index of Fibonacci number closest to n
 */
export function fibonacciIndex(n: number): number {
  if (n <= 1) return n;
  
  // Using inverse Binet: i ≈ log_φ(n · √5)
  const index = Math.round(Math.log(n * SQRT_5) / Math.log(φ));
  return Math.max(0, index);
}

/**
 * Next Fibonacci number greater than n
 */
export function nextFibonacci(n: number): number {
  let a = 0;
  let b = 1;
  while (b <= n) {
    const temp = a + b;
    a = b;
    b = temp;
  }
  return b;
}

/**
 * GOLDEN SPIRAL POINT
 * 
 * Points on a Fermat spiral with golden angle separation:
 *   θ_n = n · GOLDEN_ANGLE
 *   r_n = c · √n
 * 
 * This gives uniform distribution on a disk.
 */
export function goldenSpiralPoint(n: number, scale: number = 1): Vec2 {
  const theta = n * GOLDEN_ANGLE;
  const r = scale * Math.sqrt(n);
  return {
    x: r * Math.cos(theta),
    y: r * Math.sin(theta)
  };
}

/**
 * FIBONACCI SPHERE POINT
 * 
 * Uniform distribution of points on a sphere using Fibonacci lattice:
 *   θ = n · GOLDEN_ANGLE
 *   y = 1 - 2n/(N-1)
 *   r_xz = √(1 - y²)
 *   x = r_xz · cos(θ)
 *   z = r_xz · sin(θ)
 */
export function fibonacciSpherePoint(n: number, totalPoints: number): Vec3 {
  const theta = n * GOLDEN_ANGLE;
  const y = 1 - (2 * n / (totalPoints - 1));
  const radiusAtY = Math.sqrt(1 - y * y);
  
  return {
    x: radiusAtY * Math.cos(theta),
    y: y,
    z: radiusAtY * Math.sin(theta)
  };
}

/**
 * GOLDEN RATIO POWERS
 * 
 * Powers of φ satisfy: φⁿ = F(n)·φ + F(n-1)
 * where F(n) is the nth Fibonacci number.
 */
export function phiPower(n: number): number {
  if (n === 0) return 1;
  if (n === 1) return φ;
  if (n < 0) return Math.pow(ψ, -n);
  return Math.pow(φ, n);
}

