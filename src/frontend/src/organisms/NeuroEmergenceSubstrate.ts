/**
 * TICK ORGANISM SUBSTRATE — Main update function
 */
export function tickOrganismSubstrate(
  state: OrganismSubstrateState,
  externalInput: {
    energy: number;
    stimuli: number[];
  }
): OrganismSubstrateState {
  const dt = state.dt;
  const beat = state.beat + 1;
  const elapsedTime = state.elapsedTime + dt;
  
  // 1. Update Kuramoto network
  const newKuramotoNetwork = tickKuramotoNetwork(state.kuramotoNetwork, dt);
  
  // 2. Update heartbeat (Van der Pol)
  const newHeartbeat = integrateVanDerPol(state.heartbeat, 0, dt);
  const heartbeatPhase = Math.atan2(newHeartbeat.v / state.heartbeat.omega, newHeartbeat.x);
  
  // 3. Update Fibonacci timing
  let fibonacciBeat = state.fibonacciBeat;
  let nextFibonacciEvent = state.nextFibonacciEvent;
  
  if (beat >= nextFibonacciEvent) {
    fibonacciBeat = fibonacciIndex(beat);
    nextFibonacciEvent = nextFibonacci(beat);
  }
  
  const goldenSpiralPhase = (beat * GOLDEN_ANGLE) % τ;
  
  // 4. Update shells with Kuramoto coupling
  const newShells = state.shells.map((shell, i) => {
    // Couple shell phase to global mean phase
    const coupling = 0.1 * newKuramotoNetwork.rGlobal * 
                    Math.sin(newKuramotoNetwork.psiGlobal - shell.phase);
    let newPhase = shell.phase + (τ / 12 * (i + 1) * 0.01) + coupling;
    while (newPhase >= τ) newPhase -= τ;
    while (newPhase < 0) newPhase += τ;
    
    // Update activation based on stimuli
    const stimulusIndex = i % externalInput.stimuli.length;
    const stimulus = externalInput.stimuli[stimulusIndex] || 0;
    const newActivation = shell.activation * 0.9 + stimulus * 0.1;
    
    return {
      ...shell,
      phase: newPhase,
      activation: Math.max(SIGMA_ZERO, Math.min(1, newActivation)),
      coherence: newKuramotoNetwork.rGlobal
    };
  });
  
  // 5. Compute global metrics
  const globalCoherence = newKuramotoNetwork.rGlobal;
  const globalEntropy = newKuramotoNetwork.entropy;
  const globalEnergy = state.globalEnergy * 0.999 + externalInput.energy * 0.001;
  
  // 6. Update coherence history
  const coherenceHistory = [globalCoherence, ...state.coherenceHistory.slice(0, 99)];
  
  // 7. Compute sovereignty (based on coherence stability)
  const coherenceVariance = coherenceHistory.length > 1
    ? coherenceHistory.reduce((sum, c, i, arr) => {
        if (i === 0) return 0;
        return sum + Math.pow(c - arr[i-1], 2);
      }, 0) / coherenceHistory.length
    : 0;
  const sovereigntyLevel = Math.max(SIGMA_ZERO, 
    globalCoherence * (1 - coherenceVariance * 10)
  );
  
  return {
    ...state,
    beat,
    elapsedTime,
    kuramotoNetwork: newKuramotoNetwork,
    heartbeat: newHeartbeat,
    heartbeatPhase,
    fibonacciBeat,
    nextFibonacciEvent,
    goldenSpiralPhase,
    globalCoherence,
    globalEntropy,
    globalEnergy,
    shells: newShells,
    sovereigntyLevel,
    coherenceHistory
  };
}

