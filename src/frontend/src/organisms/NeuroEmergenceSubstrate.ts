export const Vec3Math = {
  // Create vectors
  zero: (): Vec3 => ({ x: 0, y: 0, z: 0 }),
  one: (): Vec3 => ({ x: 1, y: 1, z: 1 }),
  up: (): Vec3 => ({ x: 0, y: 1, z: 0 }),
  forward: (): Vec3 => ({ x: 0, y: 0, z: 1 }),
  right: (): Vec3 => ({ x: 1, y: 0, z: 0 }),

  // Basic operations
  add: (a: Vec3, b: Vec3): Vec3 => ({
    x: a.x + b.x,
    y: a.y + b.y,
    z: a.z + b.z
  }),

  sub: (a: Vec3, b: Vec3): Vec3 => ({
    x: a.x - b.x,
    y: a.y - b.y,
    z: a.z - b.z
  }),

  mul: (a: Vec3, b: Vec3): Vec3 => ({
    x: a.x * b.x,
    y: a.y * b.y,
    z: a.z * b.z
  }),

  div: (a: Vec3, b: Vec3): Vec3 => ({
    x: b.x !== 0 ? a.x / b.x : 0,
    y: b.y !== 0 ? a.y / b.y : 0,
    z: b.z !== 0 ? a.z / b.z : 0
  }),

  scale: (v: Vec3, s: number): Vec3 => ({
    x: v.x * s,
    y: v.y * s,
    z: v.z * s
  }),

  negate: (v: Vec3): Vec3 => ({
    x: -v.x,
    y: -v.y,
    z: -v.z
  }),

  // Dot product: a · b = |a||b|cos(θ)
  dot: (a: Vec3, b: Vec3): number => 
    a.x * b.x + a.y * b.y + a.z * b.z,

  // Cross product: a × b = |a||b|sin(θ)n̂
  cross: (a: Vec3, b: Vec3): Vec3 => ({
    x: a.y * b.z - a.z * b.y,
    y: a.z * b.x - a.x * b.z,
    z: a.x * b.y - a.y * b.x
  }),

  // Length (magnitude): |v| = √(x² + y² + z²)
  length: (v: Vec3): number => 
    Math.sqrt(v.x * v.x + v.y * v.y + v.z * v.z),

  // Squared length (faster, no sqrt)
  lengthSquared: (v: Vec3): number => 
    v.x * v.x + v.y * v.y + v.z * v.z,

  // Distance between two points
  distance: (a: Vec3, b: Vec3): number => 
    Vec3Math.length(Vec3Math.sub(b, a)),

  distanceSquared: (a: Vec3, b: Vec3): number => 
    Vec3Math.lengthSquared(Vec3Math.sub(b, a)),

  // Normalize: v̂ = v / |v|
  normalize: (v: Vec3): Vec3 => {
    const len = Vec3Math.length(v);
    if (len < 0.000001) return Vec3Math.zero();
    return Vec3Math.scale(v, 1 / len);
  },

  // Linear interpolation: lerp(a, b, t) = a + t(b - a)
  lerp: (a: Vec3, b: Vec3, t: number): Vec3 => ({
    x: a.x + t * (b.x - a.x),
    y: a.y + t * (b.y - a.y),
    z: a.z + t * (b.z - a.z)
  }),

  // Spherical linear interpolation (for smooth rotation paths)
  slerp: (a: Vec3, b: Vec3, t: number): Vec3 => {
    const dot = Vec3Math.dot(Vec3Math.normalize(a), Vec3Math.normalize(b));
    const theta = Math.acos(Math.max(-1, Math.min(1, dot)));
    
    if (Math.abs(theta) < 0.001) {
      return Vec3Math.lerp(a, b, t);
    }
    
    const sinTheta = Math.sin(theta);
    const wa = Math.sin((1 - t) * theta) / sinTheta;
    const wb = Math.sin(t * theta) / sinTheta;
    
    return Vec3Math.add(
      Vec3Math.scale(a, wa),
      Vec3Math.scale(b, wb)
    );
  },

  // Reflect vector around normal: r = v - 2(v · n)n
  reflect: (v: Vec3, normal: Vec3): Vec3 => {
    const dot2 = 2 * Vec3Math.dot(v, normal);
    return Vec3Math.sub(v, Vec3Math.scale(normal, dot2));
  },

  // Project a onto b: proj_b(a) = (a · b / |b|²) b
  project: (a: Vec3, b: Vec3): Vec3 => {
    const bLenSq = Vec3Math.lengthSquared(b);
    if (bLenSq < 0.000001) return Vec3Math.zero();
    const scalar = Vec3Math.dot(a, b) / bLenSq;
    return Vec3Math.scale(b, scalar);
  },

  // Angle between vectors: θ = acos(a · b / (|a||b|))
  angle: (a: Vec3, b: Vec3): number => {
    const dot = Vec3Math.dot(a, b);
    const lenProduct = Vec3Math.length(a) * Vec3Math.length(b);
    if (lenProduct < 0.000001) return 0;
    return Math.acos(Math.max(-1, Math.min(1, dot / lenProduct)));
  },

  // Rotate around axis by angle (Rodrigues' rotation formula)
  rotateAroundAxis: (v: Vec3, axis: Vec3, angle: number): Vec3 => {
    const k = Vec3Math.normalize(axis);
    const cosA = Math.cos(angle);
    const sinA = Math.sin(angle);
    
    // v_rot = v·cos(θ) + (k × v)·sin(θ) + k·(k · v)·(1 - cos(θ))
    const term1 = Vec3Math.scale(v, cosA);
    const term2 = Vec3Math.scale(Vec3Math.cross(k, v), sinA);
    const term3 = Vec3Math.scale(k, Vec3Math.dot(k, v) * (1 - cosA));
    
    return Vec3Math.add(Vec3Math.add(term1, term2), term3);
  },

  // Convert to spherical coordinates
  toSpherical: (v: Vec3): SphericalCoord => {
    const r = Vec3Math.length(v);
    if (r < 0.000001) {
      return { r: 0, theta: 0, phi: 0 };
    }
    return {
      r,
      theta: Math.atan2(v.z, v.x),
      phi: Math.acos(Math.max(-1, Math.min(1, v.y / r)))
    };
  },

  // Convert from spherical coordinates
  fromSpherical: (s: SphericalCoord): Vec3 => ({
    x: s.r * Math.sin(s.phi) * Math.cos(s.theta),
    y: s.r * Math.cos(s.phi),
    z: s.r * Math.sin(s.phi) * Math.sin(s.theta)
  }),

  // Clamp each component
  clamp: (v: Vec3, min: Vec3, max: Vec3): Vec3 => ({
    x: Math.max(min.x, Math.min(max.x, v.x)),
    y: Math.max(min.y, Math.min(max.y, v.y)),
    z: Math.max(min.z, Math.min(max.z, v.z))
  }),

  // Component-wise min/max
  min: (a: Vec3, b: Vec3): Vec3 => ({
    x: Math.min(a.x, b.x),
    y: Math.min(a.y, b.y),
    z: Math.min(a.z, b.z)
  }),

  max: (a: Vec3, b: Vec3): Vec3 => ({
    x: Math.max(a.x, b.x),
    y: Math.max(a.y, b.y),
    z: Math.max(a.z, b.z)
  }),

  // Check equality within epsilon
  equals: (a: Vec3, b: Vec3, epsilon: number = 0.000001): boolean =>
    Math.abs(a.x - b.x) < epsilon &&
    Math.abs(a.y - b.y) < epsilon &&
    Math.abs(a.z - b.z) < epsilon
};

