export const ComplexMath = {
  // Create complex numbers
  zero: (): Complex => ({ real: 0, imag: 0 }),
  one: (): Complex => ({ real: 1, imag: 0 }),
  i: (): Complex => ({ real: 0, imag: 1 }),
  
  fromPolar: (r: number, theta: number): Complex => ({
    real: r * Math.cos(theta),
    imag: r * Math.sin(theta)
  }),

  // Basic operations
  add: (a: Complex, b: Complex): Complex => ({
    real: a.real + b.real,
    imag: a.imag + b.imag
  }),

  sub: (a: Complex, b: Complex): Complex => ({
    real: a.real - b.real,
    imag: a.imag - b.imag
  }),

  // (a + bi)(c + di) = (ac - bd) + (ad + bc)i
  mul: (a: Complex, b: Complex): Complex => ({
    real: a.real * b.real - a.imag * b.imag,
    imag: a.real * b.imag + a.imag * b.real
  }),

  // (a + bi)/(c + di) = [(ac + bd) + (bc - ad)i] / (c² + d²)
  div: (a: Complex, b: Complex): Complex => {
    const denom = b.real * b.real + b.imag * b.imag;
    if (denom < 0.000001) return ComplexMath.zero();
    return {
      real: (a.real * b.real + a.imag * b.imag) / denom,
      imag: (a.imag * b.real - a.real * b.imag) / denom
    };
  },

  scale: (z: Complex, s: number): Complex => ({
    real: z.real * s,
    imag: z.imag * s
  }),

  // Conjugate: (a + bi)* = a - bi
  conjugate: (z: Complex): Complex => ({
    real: z.real,
    imag: -z.imag
  }),

  // Magnitude: |z| = √(a² + b²)
  magnitude: (z: Complex): number =>
    Math.sqrt(z.real * z.real + z.imag * z.imag),

  magnitudeSquared: (z: Complex): number =>
    z.real * z.real + z.imag * z.imag,

  // Argument (phase): arg(z) = atan2(b, a)
  argument: (z: Complex): number =>
    Math.atan2(z.imag, z.real),

  // Euler's formula: e^(iθ) = cos(θ) + i·sin(θ)
  exp: (z: Complex): Complex => {
    const expReal = Math.exp(z.real);
    return {
      real: expReal * Math.cos(z.imag),
      imag: expReal * Math.sin(z.imag)
    };
  },

  // Natural logarithm: ln(z) = ln|z| + i·arg(z)
  log: (z: Complex): Complex => ({
    real: Math.log(ComplexMath.magnitude(z)),
    imag: ComplexMath.argument(z)
  }),

  // Power: z^n using De Moivre's theorem
  pow: (z: Complex, n: number): Complex => {
    const r = ComplexMath.magnitude(z);
    const theta = ComplexMath.argument(z);
    const newR = Math.pow(r, n);
    const newTheta = n * theta;
    return ComplexMath.fromPolar(newR, newTheta);
  },

  // Square root
  sqrt: (z: Complex): Complex => {
    const r = ComplexMath.magnitude(z);
    const theta = ComplexMath.argument(z);
    return ComplexMath.fromPolar(Math.sqrt(r), theta / 2);
  },

  // Trigonometric functions
  sin: (z: Complex): Complex => {
    // sin(z) = (e^(iz) - e^(-iz)) / (2i)
    const iz = { real: -z.imag, imag: z.real };
    const negIz = { real: z.imag, imag: -z.real };
    const expIz = ComplexMath.exp(iz);
    const expNegIz = ComplexMath.exp(negIz);
    const diff = ComplexMath.sub(expIz, expNegIz);
    return ComplexMath.div(diff, { real: 0, imag: 2 });
  },

  cos: (z: Complex): Complex => {
    // cos(z) = (e^(iz) + e^(-iz)) / 2
    const iz = { real: -z.imag, imag: z.real };
    const negIz = { real: z.imag, imag: -z.real };
    const expIz = ComplexMath.exp(iz);
    const expNegIz = ComplexMath.exp(negIz);
    const sum = ComplexMath.add(expIz, expNegIz);
    return ComplexMath.scale(sum, 0.5);
  }
};

