export interface HebbianNeuron {
  id: number;
  activation: number;        // Current activation [0, 1]
  threshold: number;         // Firing threshold
  refractoryRemaining: number; // Refractory period remaining
  lastSpikeTime: number;     // Time of last spike
  spikeHistory: number[];    // Recent spike times
  adaptationCurrent: number; // Spike frequency adaptation
  calciumLevel: number;      // Ca²⁺ for plasticity gating
}

export interface HebbianSynapse {
  preId: number;
  postId: number;
  weight: number;
  delay: number;
  type: 'excitatory' | 'inhibitory';
  eligibilityTrace: number;  // For reward-modulated learning
}

export interface HebbianNetwork {
  neurons: HebbianNeuron[];
  synapses: HebbianSynapse[];
  N: number;
  eta: number;               // Learning rate
  A_plus: number;            // LTP amplitude
  A_minus: number;           // LTD amplitude
  tau_plus: number;          // LTP time constant
  tau_minus: number;         // LTD time constant
  wMax: number;              // Maximum weight
  wMin: number;              // Minimum weight
  beat: number;
}

/**
 * SPIKE-TIMING DEPENDENT PLASTICITY (STDP)
 * 
 * STDP kernel:
 *   Δw = A₊·exp(-Δt/τ₊)  if Δt > 0 (pre before post: LTP)
 *   Δw = -A₋·exp(Δt/τ₋)  if Δt < 0 (post before pre: LTD)
 * 
 * Where Δt = t_post - t_pre
 */
export function computeSTDP(
  deltaT: number,
  A_plus: number,
  A_minus: number,
  tau_plus: number,
  tau_minus: number
): number {
  if (Math.abs(deltaT) > 100) return 0; // Too far apart
  
  if (deltaT > 0) {
    // Pre before post: Long-term potentiation (LTP)
    return A_plus * Math.exp(-deltaT / tau_plus);
  } else if (deltaT < 0) {
    // Post before pre: Long-term depression (LTD)
    return -A_minus * Math.exp(deltaT / tau_minus);
  }
  return 0;
}

/**
 * HEBBIAN WEIGHT UPDATE
 * 
 * Classic Hebbian rule with STDP:
 *   Δwᵢⱼ = Σ_spikes STDP(t_post - t_pre) · gate(Ca²⁺)
 * 
 * The calcium level gates plasticity (BCM-like rule).
 */
export function updateHebbianWeight(
  synapse: HebbianSynapse,
  preNeuron: HebbianNeuron,
  postNeuron: HebbianNeuron,
  network: HebbianNetwork
): number {
  let deltaW = 0;
  
  // Sum STDP contributions from all spike pairs
  for (const tPre of preNeuron.spikeHistory) {
    for (const tPost of postNeuron.spikeHistory) {
      const deltaT = tPost - tPre;
      if (Math.abs(deltaT) < 100) {
        const stdp = computeSTDP(
          deltaT,
          network.A_plus,
          network.A_minus,
          network.tau_plus,
          network.tau_minus
        );
        
        // Weight-dependent scaling (soft bounds)
        const weightFactor = deltaT > 0 
          ? (network.wMax - synapse.weight) / network.wMax
          : (synapse.weight - network.wMin) / network.wMax;
        
        deltaW += stdp * weightFactor;
      }
    }
  }
  
  // Calcium gating
  const plasticityGate = Math.tanh(postNeuron.calciumLevel * 5);
  deltaW *= network.eta * plasticityGate;
  
  // Apply bounds
  let newWeight = synapse.weight + deltaW;
  newWeight = Math.max(network.wMin, Math.min(network.wMax, newWeight));
  
  return newWeight;
}

/**
 * LEAKY INTEGRATE-AND-FIRE (LIF) NEURON UPDATE
 * 
 * τₘ·dV/dt = -(V - V_rest) + R·I
 * if V > V_thresh: spike, V → V_reset
 */
export function updateLIFNeuron(
  neuron: HebbianNeuron,
  synapticInput: number,
  dt: number
): HebbianNeuron {
  const tau_m = 20;        // Membrane time constant (ms)
  const tau_a = 100;       // Adaptation time constant
  const tau_Ca = 50;       // Calcium time constant
  const V_rest = -70;      // Resting potential (mV)
  const V_thresh = -55;    // Threshold
  const V_reset = -75;     // Reset
  const R = 10;            // Membrane resistance
  const delta_a = 0.1;     // Adaptation increment
  const delta_Ca = 0.2;    // Calcium increment
  const refractoryPeriod = 2;
  
  // Check refractory period
  if (neuron.refractoryRemaining > 0) {
    return {
      ...neuron,
      refractoryRemaining: neuron.refractoryRemaining - 1
    };
  }
  
  // Estimate voltage from activation (normalized)
  const V_current = V_rest + neuron.activation * (V_thresh - V_rest);
  
  // Membrane dynamics
  const dV = (-(V_current - V_rest) + R * synapticInput) / tau_m * dt;
  let V_new = V_current + dV;
  
  // Adaptation decay
  const adaptation_new = neuron.adaptationCurrent * Math.exp(-dt / tau_a);
  
  // Calcium decay
  const calcium_new = neuron.calciumLevel * Math.exp(-dt / tau_Ca);
  
  // Effective threshold with adaptation
  const effectiveThreshold = V_thresh + adaptation_new * 10;
  
  // Spike detection
  let spiked = false;
  let newSpikeHistory = neuron.spikeHistory;
  let newAdaptation = adaptation_new;
  let newCalcium = calcium_new;
  
  if (V_new > effectiveThreshold) {
    spiked = true;
    V_new = V_reset;
    newAdaptation += delta_a;
    newCalcium += delta_Ca;
    
    // Update spike history (keep last 10)
    newSpikeHistory = [Date.now(), ...neuron.spikeHistory.slice(0, 9)];
  }
  
  // Convert voltage back to activation
  const activation_new = Math.max(0, Math.min(1, 
    (V_new - V_rest) / (V_thresh - V_rest)
  ));
  
  return {
    ...neuron,
    activation: activation_new,
    refractoryRemaining: spiked ? refractoryPeriod : 0,
    lastSpikeTime: spiked ? Date.now() : neuron.lastSpikeTime,
    spikeHistory: newSpikeHistory,
    adaptationCurrent: newAdaptation,
    calciumLevel: newCalcium
  };
}

