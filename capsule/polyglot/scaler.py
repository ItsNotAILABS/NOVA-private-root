#!/usr/bin/env python3
"""Scale layer for NOVA polyglot coding capsules.

This module adds project/session orchestration, template generation, artifact
hash manifests, and deploy handoff packets without pretending public deployment
already exists.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import time
import uuid
from dataclasses import asdict, dataclass
from typing import Any

ROOT = pathlib.Path(__file__).resolve().parent
DEFAULT_WORKSPACE_ROOT = ROOT / "workspace"
DEFAULT_DEPLOY_ROOT = ROOT / "deployments"


@dataclass(frozen=True)
class CapsuleSession:
    session_id: str
    project: str
    workspace: str
    preview_url: str
    status: str
    created_at: float
    updated_at: float

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def _sessions_path(workspace_root: pathlib.Path) -> pathlib.Path:
    return workspace_root / ".nova" / "sessions.json"


def _read_json(path: pathlib.Path, default: Any) -> Any:
    if not path.exists():
        return default
    return json.loads(path.read_text(encoding="utf-8"))


def _write_json(path: pathlib.Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True), encoding="utf-8")


def safe_name(name: str) -> str:
    cleaned = "".join(ch.lower() if ch.isalnum() else "-" for ch in name.strip())
    cleaned = "-".join(part for part in cleaned.split("-") if part)
    return cleaned or "nova-project"


def create_session(project: str = "nova-project", workspace_root: str | None = None) -> dict[str, Any]:
    root = pathlib.Path(workspace_root or DEFAULT_WORKSPACE_ROOT).resolve()
    root.mkdir(parents=True, exist_ok=True)
    project_name = safe_name(project)
    session_id = uuid.uuid4().hex
    workspace = root / "sessions" / session_id / project_name
    preview = workspace / "preview"
    preview.mkdir(parents=True, exist_ok=True)
    now = time.time()
    session = CapsuleSession(
        session_id=session_id,
        project=project_name,
        workspace=str(workspace),
        preview_url=f"/preview/{session_id}/index.html",
        status="active",
        created_at=now,
        updated_at=now,
    )
    sessions = _read_json(_sessions_path(root), [])
    sessions.append(session.to_dict())
    _write_json(_sessions_path(root), sessions)
    return session.to_dict()


def list_sessions(workspace_root: str | None = None) -> list[dict[str, Any]]:
    root = pathlib.Path(workspace_root or DEFAULT_WORKSPACE_ROOT).resolve()
    return _read_json(_sessions_path(root), [])


