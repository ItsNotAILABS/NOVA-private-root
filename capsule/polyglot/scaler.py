def init_project(workspace: str, kind: str = "web") -> dict[str, Any]:
    root = pathlib.Path(workspace).resolve()
    root.mkdir(parents=True, exist_ok=True)
    files = project_template(kind)
    written: list[str] = []
    for name, content in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(name)
    return {"ok": True, "workspace": str(root), "kind": kind, "files": written}


def hash_file(path: pathlib.Path, root: pathlib.Path) -> dict[str, Any]:
    data = path.read_bytes()
    return {
        "path": str(path.relative_to(root)),
        "bytes": len(data),
        "sha256": hashlib.sha256(data).hexdigest(),
    }


def build_hash_manifest(workspace: str, include_receipts: bool = True) -> dict[str, Any]:
    root = pathlib.Path(workspace).resolve()
    files: list[dict[str, Any]] = []
    for path in sorted(root.rglob("*")):
        if not path.is_file():
            continue
        if not include_receipts and ".nova" in path.parts:
            continue
        files.append(hash_file(path, root))
    manifest = {
        "schema": "nova.polyglot.hash-manifest.v1",
        "workspace": str(root),
        "generated_at": time.time(),
        "file_count": len(files),
        "files": files,
    }
    out = root / ".nova" / "hash-manifest.json"
    _write_json(out, manifest)
    return manifest


def build_deploy_packet(workspace: str, target: str = "github-handoff") -> dict[str, Any]:
    root = pathlib.Path(workspace).resolve()
    manifest = build_hash_manifest(str(root))
    packet = {
        "schema": "nova.polyglot.deploy-packet.v1",
        "target": target,
        "workspace": str(root),
        "generated_at": time.time(),
        "status": "ready-for-handoff",
        "boundary": "local deploy packet only; no public external deployment claimed",
        "manifest_path": str(root / ".nova" / "hash-manifest.json"),
        "file_count": manifest["file_count"],
    }
    _write_json(root / ".nova" / "deploy-packet.json", packet)
    return packet
